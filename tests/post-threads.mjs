import assert from 'node:assert/strict';
import {createHash,randomUUID} from 'node:crypto';
import {database} from '../scripts/db-adapter.mjs';
import worker from '../server/worker.js';
import {flattenPosts,revealReply,replyBranch,createPostRenderer} from '../client/post-threads.js';
const DB=database(),env={DB},now=Date.now(),tokens={a:'a'.repeat(64),b:'b'.repeat(64),c:'c'.repeat(64)};
for(const id of Object.keys(tokens)){
 DB.native.prepare('INSERT INTO users VALUES(?,?,?,?,?,?,?)').run(id,id==='a'?'Nockcho':id,id,'unused','member','active',now);
 DB.native.prepare('INSERT INTO characters(id,user_id,name,created_at,updated_at) VALUES(?,?,?,?,?)').run(id,id,id,now,now);
 DB.native.prepare('INSERT INTO sessions VALUES(?,?,?)').run(createHash('sha256').update(tokens[id]).digest('hex'),id,now+600000);
}
async function call(path,{user='a',method='GET',data,status=200,key}={}){
 const response=await worker.fetch(new Request('https://test.example/api'+path,{method,headers:{'x-requested-with':'usual-saviors',cookie:'us_session='+tokens[user],...(data?{'content-type':'application/json'}:{}),...(key?{'idempotency-key':key}:{})},body:data?JSON.stringify(data):undefined}),env);
 const result=await response.json();assert.equal(response.status,status,JSON.stringify(result));return result;
}
const write=(user,parentId,body='reply',key)=>call('/posts',{user,method:'POST',data:{characterId:user,parentId,body},status:201,key});
const root=await write('a',null,'root'),reply=await write('b',root.id),nested=await write('c',reply.id);
assert.equal(nested.rootId,root.id);
const retryKey=randomUUID(),last=await write('a',nested.id,'deep',retryKey);
assert.deepEqual(await write('a',nested.id,'deep',retryKey),last);
let thread=(await call('/posts/'+nested.id)).item;
assert.deepEqual(flattenPosts([thread]).map(p=>p.id),[root.id,reply.id,nested.id,last.id]);
assert.equal((await call('/notifications',{user:'b'})).items[0].reply_id,nested.id);
assert.equal((await call('/notifications',{user:'b'})).items[0].target_id,root.id);
await call('/posts/'+last.id,{method:'PATCH',data:{body:'deep edit'}});
assert.equal(flattenPosts([(await call('/posts/'+root.id)).item]).at(-1).body,'deep edit');
DB.native.prepare("UPDATE users SET status='suspended' WHERE id='b'").run();
assert.equal((await call('/posts/'+root.id)).item.replies.length,0);
assert.equal((await call('/notifications',{user:'c'})).items.length,0);
await call('/posts',{method:'POST',data:{characterId:'a',parentId:nested.id,body:'hidden ancestor'},status:400});
DB.native.prepare("UPDATE users SET status='active' WHERE id='b'").run();
const expanded=new Set();revealReply([thread],last.id,expanded);assert.deepEqual([...expanded],[nested.id,reply.id,root.id]);
const visibleThreads=new Set();
const render=createPostRenderer({state:{user:{id:'a'}},escape:v=>String(v),button:(label,action,cls='',attrs='')=>`<button data-do="${action}" ${attrs}>${label}</button>`,face:()=>'',date:()=>'',canEdit:()=>true,mine:()=>[{}],expanded:visibleThreads});
const html=render(thread);assert.equal((html.match(/data-do="reply:/g)||[]).length,2,'timeline shows root and direct replies only');
assert.equal((html.match(/class="post-replies"/g)||[]).length,1,'all replies share one list instead of shrinking nested containers');
assert.equal((html.match(/data-thread-depth="1"/g)||[]).length,1,'nested conversation stays out of the timeline');
assert.equal((html.match(/class="reply-context"/g)||[]).length,1,'direct reply identifies its parent author');
assert.ok(html.includes('thread-open:'+reply.id));
assert.ok(!html.includes('data-record="'+nested.id+'"'));
assert.equal(replyBranch([thread],last.id).id,reply.id,'deep notification resolves directly to its conversation window');
assert.equal(replyBranch([thread],reply.id),null,'direct reply stays in timeline');
const branch=thread.replies[0],other={id:'other',name:'Other',body:'unrelated',replies:[]};thread.replies.push(other);
const windowHTML=render(branch,0,null,true);
assert.equal((windowHTML.match(/data-do="reply:/g)||[]).length,3,'window retains reply actions at every level');
assert.ok(!windowHTML.includes('unrelated'),'other characters conversations stay outside the window');
assert.doesNotMatch(windowHTML,/thread-open:|toggle-replies:|class="post-replies"[^>]+hidden/,'one window reveals the complete selected conversation');
assert.equal((windowHTML.match(/data-thread-depth="1"/g)||[]).length,2,'window rows keep a constant width');
thread.replies.pop();
assert.equal((html.match(/class="post-replies"[^>]+hidden/g)||[]).length,1,'only the whole conversation starts folded');
assert.equal((html.match(/data-do="toggle-replies:/g)||[]).length,1,'nested replies never require another expand click');
visibleThreads.add(root.id);
assert.doesNotMatch(render(thread),/class="post-replies"[^>]+hidden/,'one expansion reveals all descendants');
visibleThreads.clear();revealReply([thread],last.id,visibleThreads);
assert.doesNotMatch(render(thread),/class="post-replies"[^>]+hidden/,'notification opens the full path to the deepest reply');
visibleThreads.delete(root.id);
assert.equal((render(thread).match(/class="post-replies"[^>]+hidden/g)||[]).length,1,'the entire conversation can still be collapsed');
await call('/posts/'+reply.id,{user:'b',method:'DELETE'});
assert.equal((await call('/posts/'+root.id)).item.replies.length,0);
assert.equal(DB.native.prepare('SELECT COUNT(*) n FROM posts').get().n,1,'deletion removes every descendant');
const x=await write('b',root.id),y=await write('c',x.id);await write('a',y.id);
DB.native.prepare("DELETE FROM characters WHERE id='b'").run();
assert.equal(DB.native.prepare('SELECT COUNT(*) n FROM posts').get().n,1,'character deletion cannot strand nested replies');
DB.native.close();console.log('Nested replies, targeted notifications, hidden ancestors, folding and recursive deletion verified.');
